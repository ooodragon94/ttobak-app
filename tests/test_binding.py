"""서버를 어디에 열어 두는가 — 보안 기본값 고정.

이 파일은 기능을 재지 않는다. **기본값이 조용히 넓어지는 것**을 막는다.
바인딩 주소는 한 글자 바꾸면 공격 면이 통째로 달라지는데, 코드 리뷰에서는
눈에 잘 띄지 않는 종류의 변경이다.
"""

from __future__ import annotations

from ttobak.config import Settings


def test_기본_바인딩은_로컬호스트다() -> None:
    """바깥에서는 앞단(터널·프록시)을 거쳐 들어오지 같은 Wi-Fi 로 들어오지 않는다.

    앞단은 이 서버를 127.0.0.1 로 찾으므로 로컬호스트에만 열어도 외부 접속은
    그대로 된다. 0.0.0.0 은 같은 공유기에 붙은 아무 기기에나 문을 하나 더 열어
    줄 뿐이고, 그 경로는 앞단의 보호를 거치지 않는다.
    """
    assert Settings().host == "127.0.0.1"


def test_원하면_넓힐_수_있다() -> None:
    """보안 기본값이지 금지가 아니다. 필요할 때 여는 길은 남아 있어야 한다."""
    assert Settings(host="0.0.0.0").host == "0.0.0.0"
