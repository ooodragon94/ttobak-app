"""후원 단계.

광고 대신 이걸 먼저 넣는 이유
-----------------------------

애드센스는 **$100(약 13만 원)이 쌓여야 지급한다.** 친구 100명 규모에서는 그
선까지 몇 년이 걸리고, 그동안 통장에는 0원이다. 후원은 그 문턱이 없다 —
누가 한 번 누르면 그날 들어온다.

금액을 왜 이렇게 나눴나
-----------------------

"후원하기" 버튼 하나만 두면 **얼마를 내야 할지 몰라서 아무도 안 누른다.**
사람은 빈칸보다 보기를 잘 고른다.

그래서 실제로 아는 물건의 값으로 적었다. "1,000원"보다 "카누 한 잔"이
얼마인지 바로 그려진다. 제일 아래를 300원짜리 사탕으로 둔 것도 의도다 —
가장 싼 선택지가 부담 없어야 그 위를 쳐다본다. 스타벅스를 맨 위에 둔 것도
같은 이유다. 제일 비싼 것이 있어야 가운데가 적당해 보인다.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = ["SUPPORT_TIERS", "SUPPORT_PROVIDERS", "SupportProvider", "SupportTier"]


@dataclass(frozen=True)
class SupportTier:
    """후원 한 단계."""

    #: 화면에 크게 띄울 이모지.
    emoji: str
    #: 무엇을 사 주는 셈인지.
    label: str
    #: 원화 금액.
    amount: int
    #: 버튼 아래 붙는 한마디. 부담을 덜어 주는 것이 목적이다.
    note: str

    @property
    def amount_text(self) -> str:
        """``1,000원`` 처럼 천 단위를 끊어 준다."""
        return f"{self.amount:,}원"


#: 후원 단계. 싼 것부터 둔다 — 처음 보이는 것이 제일 부담 없어야 한다.
#:
#: 간격을 촘촘하게 둔 이유: 300원과 1,000원 사이가 비어 있으면 "300은 너무
#: 성의 없나" 싶은 사람이 갈 곳이 없어 그냥 안 누른다. 500원 칸이 그 사이를
#: 메운다. 칸이 많아 보이지만 세로로 늘어놓으므로 화면이 복잡해지지 않는다.
#:
#: 한마디는 **명사 하나로 끝낸다.**
#:
#: "서버비 보태 주세요" 라고 쓰면 후원이 부탁이 되고, 안 누른 사람은
#: 미안해진다. 친구들끼리 하는 게임에서 만들면 안 되는 감정이다.
#: 그냥 "전기세" 라고만 두면 부탁도 생색도 아니고, 짧아서 눈에 잘 들어온다.
#:
#: 금액이 올라가면서 **실제로 이 게임에 드는 비용**을 따라 올라간다.
#: 껌값 → 전기세 → 서버비 → 도메인값. 농담이지만 다 진짜 나가는 돈이다.
SUPPORT_TIERS: tuple[SupportTier, ...] = (
    SupportTier("🍭", "추파춥스", 300, "껌값"),
    SupportTier("🍦", "아이스크림", 500, "용돈"),
    SupportTier("☕", "카누 한 잔", 1_000, "전기세"),
    SupportTier("🥤", "메가커피", 2_000, "서버비"),
    SupportTier("⭐", "스타벅스", 4_500, "도메인값"),
    # 마지막 칸은 **농담이다.** 아무도 안 누를 것을 알고 넣는다.
    #
    # 이런 칸이 하나 있으면 두 가지가 생긴다. 웃기고, 그 아래가 싸 보인다.
    # 4,500원이 제일 비싼 칸일 때보다 10만원 옆에 있을 때 더 만만해 보인다
    # (앵커링). 그래서 농담이면서 동시에 제 일을 한다.
    SupportTier("🖥️", "서버 한 대", 100_000, "서버 새로 좀 사라"),
)


@dataclass(frozen=True)
class SupportProvider:
    """송금 수단 하나. 토스, 카카오페이."""

    #: 설정에서 이 수단의 주소를 담는 항목 이름.
    key: str
    label: str
    emoji: str


#: 쓸 수 있는 송금 수단.
#:
#: 둘 다 두는 이유: 사람마다 깔려 있는 앱이 다르다. 토스만 두면 카카오페이만
#: 쓰는 사람은 그 자리에서 그만둔다. 한쪽만 설정해도 되고, 그러면 화면에
#: 선택지가 아예 안 나온다(하나뿐인데 고르라고 하면 군더더기다).
#:
#: 주소에 ``{amount}`` 를 넣으면 단계별 금액으로 바뀐다. 금액을 주소에 못
#: 싣는 서비스면 그냥 빼면 되고, 그때는 모든 단계가 같은 곳으로 간다.
SUPPORT_PROVIDERS: tuple[SupportProvider, ...] = (
    SupportProvider("toss", "토스", "💙"),
    SupportProvider("kakao", "카카오페이", "💛"),
)
